// Deterministically generates shell and LuCI parameter contract modules from schema/parameters.json.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export function loadSchema(repoRoot = root) {
  const schema = JSON.parse(fs.readFileSync(path.join(repoRoot, 'schema/parameters.json'), 'utf8'));
  assert.equal(schema.schemaVersion, 1, 'Unsupported parameter schemaVersion');
  return schema;
}

export function renderContractTargets(repoRoot = root) {
  const s = loadSchema(repoRoot);
  const sh = [
    '# Generated by tools/sync-schema.mjs from schema/parameters.json; do not edit.',
    '# SPDX-License-Identifier: GPL-3.0-or-later',
    `FT_SCHEMA_TTL_MIN=${s.ttl.min}`,
    `FT_SCHEMA_TTL_MAX=${s.ttl.max}`,
    `FT_SCHEMA_TTL_DEFAULT=${s.ttl.default}`,
    `FT_SCHEMA_MIN_HOPS_MIN=${s.minHops.min}`,
    `FT_SCHEMA_MIN_HOPS_MAX=${s.minHops.max}`,
    `FT_SCHEMA_MIN_HOPS_DEFAULT=${s.minHops.default}`,
    `FT_SCHEMA_NFQ_REPEAT_MIN=${s.repeat.nfqueue.min}`,
    `FT_SCHEMA_NFQ_REPEAT_MAX=${s.repeat.nfqueue.max}`,
    `FT_SCHEMA_NFQ_TCP_REPEAT_DEFAULT=${s.repeat.nfqueue.tcpDefault}`,
    `FT_SCHEMA_NFQ_UDP_REPEAT_DEFAULT=${s.repeat.nfqueue.udpDefault}`,
    `FT_SCHEMA_EBPF_REPEAT_MIN=${s.repeat.ebpf.min}`,
    `FT_SCHEMA_EBPF_REPEAT_MAX=${s.repeat.ebpf.max}`,
    `FT_SCHEMA_EBPF_REPEAT_DEFAULT=${s.repeat.ebpf.default}`,
    `FT_SCHEMA_DYNAMIC_PCT_MIN=${s.dynamicPct.min}`,
    `FT_SCHEMA_DYNAMIC_PCT_MAX=${s.dynamicPct.max}`,
    `FT_SCHEMA_DYNAMIC_PCT_DEFAULT=${s.dynamicPct.default}`,
    `FT_SCHEMA_QUEUE_TCP_MIN=${s.queue.tcpMin}`,
    `FT_SCHEMA_QUEUE_UDP_MIN=${s.queue.udpMin}`,
    `FT_SCHEMA_QUEUE_MAX=${s.queue.max}`,
    `FT_SCHEMA_QUEUE_TCP_DEFAULT=${s.queue.tcpDefault}`,
    `FT_SCHEMA_QUEUE_UDP_DEFAULT=${s.queue.udpDefault}`,
    `FT_SCHEMA_EBPF_TEMPLATE_MIN=${s.templates.ebpfMin}`,
    `FT_SCHEMA_EBPF_TEMPLATE_MAX=${s.templates.ebpfMax}`,
    `FT_SCHEMA_PAYLOAD_MIN_BYTES=${s.templates.payloadMinBytes}`,
    `FT_SCHEMA_PAYLOAD_MAX_BYTES=${s.templates.payloadMaxBytes}`,
    `FT_SCHEMA_HOSTNAME_MAX_BYTES=${s.templates.hostnameMaxBytes}`,
    `FT_SCHEMA_SIP_URI_MAX_BYTES=${s.templates.sipUriMaxBytes}`,
    `FT_SCHEMA_EBPF_MAX_DEVICES=${s.interfaces.ebpfMaxCount}`,
    `FT_SCHEMA_IFNAME_MAX_BYTES=${s.interfaces.nameMaxBytes}`,
    `FT_SCHEMA_DEFAULT_FWMARK_HEX=${s.packetContract.defaultFwmarkHex}`,
    `FT_SCHEMA_DEFAULT_FWMARK_DEC=${s.packetContract.defaultFwmarkDec}`,
    `FT_SCHEMA_DEFAULT_FWMASK_HEX=${s.packetContract.defaultFwmaskHex}`,
    `FT_SCHEMA_DEFAULT_FWMASK_DEC=${s.packetContract.defaultFwmaskDec}`,
    ''
  ].join('\n');

  const js = [
    '// Generated by tools/sync-schema.mjs from schema/parameters.json; do not edit.',
    '// SPDX-License-Identifier: GPL-3.0-or-later',
    "'use strict';",
    "'require baseclass';",
    '',
    'return baseclass.extend({',
    `\tTTL_MIN: ${s.ttl.min},`,
    `\tTTL_MAX: ${s.ttl.max},`,
    `\tTTL_DEFAULT: ${s.ttl.default},`,
    `\tMIN_HOPS_MIN: ${s.minHops.min},`,
    `\tMIN_HOPS_MAX: ${s.minHops.max},`,
    `\tMIN_HOPS_DEFAULT: ${s.minHops.default},`,
    `\tNFQ_REPEAT_MIN: ${s.repeat.nfqueue.min},`,
    `\tNFQ_REPEAT_MAX: ${s.repeat.nfqueue.max},`,
    `\tEBPF_REPEAT_MIN: ${s.repeat.ebpf.min},`,
    `\tEBPF_REPEAT_MAX: ${s.repeat.ebpf.max},`,
    `\tDYNAMIC_PCT_MIN: ${s.dynamicPct.min},`,
    `\tDYNAMIC_PCT_MAX: ${s.dynamicPct.max},`,
    `\tTCP_QUEUE_MIN: ${s.queue.tcpMin},`,
    `\tUDP_QUEUE_MIN: ${s.queue.udpMin},`,
    `\tQUEUE_MAX: ${s.queue.max},`,
    `\tTCP_QUEUE_DEFAULT: ${s.queue.tcpDefault},`,
    `\tUDP_QUEUE_DEFAULT: ${s.queue.udpDefault},`,
    `\tEBPF_TEMPLATE_MIN: ${s.templates.ebpfMin},`,
    `\tEBPF_TEMPLATE_MAX: ${s.templates.ebpfMax},`,
    `\tPAYLOAD_MAX_BYTES: ${s.templates.payloadMaxBytes}`,
    '});',
    ''
  ].join('\n');

  return new Map([
    ['openwrt/faketraffic/files/usr/libexec/faketraffic/contract.sh', sh],
    ['openwrt/luci-app-faketraffic/root/www/luci-static/resources/faketraffic/contract.js', js]
  ]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  for (const [rel, expected] of renderContractTargets(root)) {
    const file = path.join(root, rel);
    if (check) {
      assert.equal(fs.readFileSync(file, 'utf8').replaceAll('\r', ''), expected, 'Schema contract drift: ' + rel);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, expected, 'utf8');
    }
  }
  console.log('Parameter contract targets verified/generated');
}
